# Build the sprite atlas from the Pixel Art Atlas dataset (CC0):
#   1. Download and unzip pixel-art-16x16-1.4m.zip from
#      https://huggingface.co/datasets/Angais/pixel-art-atlas-1.4m into DATA_DIR
#   2. python3 tools/build-atlas.py DATA_DIR tools/sprite-picks.json public/assets [preview.png]
# sprite-picks.json maps sprite names to dataset row ids.
import json, sys
import numpy as np
from PIL import Image

data, picks_path, out = sys.argv[1], sys.argv[2], sys.argv[3]
picks = json.load(open(picks_path))
objs = json.load(open(f'{data}/objects.json', encoding='utf-8'))
tokens = np.load(f'{data}/tokens.npy', mmap_mode='r', allow_pickle=False)
palette = np.load(f'{data}/palette.npy', allow_pickle=False)
COLS = 16
names = list(picks)
rows = (len(names) + COLS - 1) // COLS
atlas = Image.new('RGBA', (COLS * 16, rows * 16), (0, 0, 0, 0))
index, credits = {}, []
for n, name in enumerate(names):
    i = picks[name]
    px = np.asarray(tokens[i]).reshape(16, 16)
    rgba = np.dstack((palette[px].astype('uint8'), ((px != 0) * 255).astype('uint8')))
    c, r = n % COLS, n // COLS
    atlas.paste(Image.fromarray(rgba, 'RGBA'), (c * 16, r * 16))
    # opaque bounds inside the 16x16 cell, so sprites can be anchored on their feet
    ys, xs = np.nonzero(px)
    index[name] = [c, r, int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1]
    credits.append(f'{name}: row {i} ({objs[i]})')
atlas.save(f'{out}/sprites.png', optimize=True)
open(f'{out}/../js/sprite-index.js', 'w').write(
    '// Generated by the atlas build: name -> [col, row, x0, y0, x1, y1] (opaque bounds in the 16x16 cell).\n'
    "'use strict';\nJJ.SPRITE_INDEX = " + json.dumps(index, separators=(',', ':')) + ';\n')
open(f'{out}/sprites-credits.txt', 'w').write(
    'Sprites selected from "Pixel Art Atlas - 1.4M Synthetic Sprites" by Angais\n'
    'https://huggingface.co/datasets/Angais/pixel-art-atlas-1.4m - CC0 1.0 (public domain dedication).\n'
    'AI-generated (Krea 2 Turbo + pixel art LoRA) per the dataset card.\n\n' + '\n'.join(credits) + '\n')
big = atlas.resize((atlas.width * 5, atlas.height * 5), Image.NEAREST)
bg = Image.new('RGBA', big.size, (70, 100, 60, 255)); bg.alpha_composite(big); bg.save(sys.argv[4] if len(sys.argv) > 4 else 'atlas-preview.png')
print(len(names), 'sprites ->', atlas.size)
